def bookmark(p, name, number):
    start=OxmlElement('w:bookmarkStart'); start.set(qn('w:id'),str(number)); start.set(qn('w:name'),name)
    end=OxmlElement('w:bookmarkEnd'); end.set(qn('w:id'),str(number))
    p._p.insert(0,start); p._p.append(end)

def fields(block):
    for key in ('code','label','title','intro','note','brief'):
        yield key,block[key], 'Heading 2' if key=='title' else None
    for i,(title,body) in enumerate(block['items']):
        yield f'item_{i}_title',title,'Heading 3'
        yield f'item_{i}_body',body,None
    if block.get('linkText'): yield 'linkText',block['linkText'],None

if not (OUT/'baseline.json').exists():
    baseline={str(p.relative_to(ROOT/'dist')):hashlib.sha256(p.read_bytes()).hexdigest() for p in (ROOT/'dist').rglob('*.html')}
    (OUT/'baseline.json').write_text(json.dumps(baseline,indent=2),encoding='utf-8')

for slug,(name,blocks) in SEEDS.items():
    source=TEXTS/f'Текст страницы - {name}.docx'
    if not source.exists(): raise FileNotFoundError(source)
    doc=Document(source)
    existing={b.get(qn('w:name')) for b in doc.element.xpath('.//w:bookmarkStart')}
    number=max([int(b.get(qn('w:id'))) for b in doc.element.xpath('.//w:bookmarkStart')]+[0])+1
    updated=False
    for n,block in enumerate(blocks):
        marker=f'license_{n}_title'
        if marker not in existing:
            doc.add_page_break()
            for key,text,style in fields(block):
                p=doc.add_paragraph(text,style=style)
                bookmark(p,f'license_{n}_{key}',number); number+=1
            updated=True
    if updated: doc.save(source)
    # Sole text source: reload each DOCX and read its bookmarks, not the seed text.
    doc=Document(source)
    values={}
    for p in doc.paragraphs:
        for b in p._p.xpath('.//w:bookmarkStart'):
            key=b.get(qn('w:name'))
            if key.startswith('license_'): values[key]=p.text
    synced=[]
    for n,seed in enumerate(blocks):
        obj={'id':seed['id']}
        for key,_,_ in fields(seed):
            if not key.startswith('item_'): obj[key]=values[f'license_{n}_{key}']
        obj['items']=[{'title':values[f'license_{n}_item_{i}_title'],'text':values[f'license_{n}_item_{i}_body']} for i in range(len(seed['items']))]
        if seed.get('link'): obj['link']=seed['link']
        synced.append(obj)
    path=ROOT/f'src/data/pages/{slug}.json'
    data=json.loads(path.read_text(encoding='utf-8-sig'))
    data['licenseSegments']=synced
    path.write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'{slug}: {len(synced)} blocks synced from DOCX')
