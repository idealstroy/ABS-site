import fs from 'node:fs/promises';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
const root='C:/Users/marke/АБС';
const qa=`${root}/tmp/slesari-core-final`;
const rows=JSON.parse(await fs.readFile(`${qa}/accepted.json`,'utf8'));
if(!rows.length) throw new Error('No verified commercial keywords');
const wb=Workbook.create();
const sheet=wb.worksheets.add('Слесари');
sheet.showGridLines=false;
sheet.getRange('A1').values=[['Слесари — коммерческое ядро /slesari/']];
const headers=['Фраза','Дата сбора','База [Bukvarix]','Точная [Bukvarix]','Регион','Источник','URL источника','Интент','Происхождение','Статус частотности','Маска-источник','URL страницы','Решение'];
sheet.getRange('A2:M2').values=[headers];
const serial=(Date.UTC(2026,9,29)-Date.UTC(1899,11,30))/86400000;
sheet.getRangeByIndexes(2,0,rows.length,13).values=rows.map(r=>[r.keyword,serial,r.frequency,r.exact,r.region,r.source,r.url,'Коммерческий поиск специалиста','Найденный запрос Bukvarix','Проверена; дата базы неизвестна',r.mask_parent,r.target,'Общий запрос слесарей; не присваивать только спецтехнике']);
sheet.getRange(`A1:M${rows.length+2}`).format.font={name:'Calibri',size:11};
sheet.getRange('A1').format.font={name:'Calibri',size:12,bold:true};
sheet.getRange('A2:M2').format={fill:'#1F4E78',font:{name:'Calibri',size:11,bold:true,color:'#FFFFFF'},wrapText:true,verticalAlignment:'center',rowHeight:42};
const widths=[35,16,18,18,16,18,45,30,32,44,32,24,49];
widths.forEach((w,i)=>sheet.getRangeByIndexes(0,i,rows.length+2,1).format.columnWidth=w);
const body=sheet.getRangeByIndexes(2,0,rows.length,13);
body.format.wrapText=true;body.format.verticalAlignment='center';body.format.rowHeight=84;
sheet.getRangeByIndexes(2,1,rows.length,1).setNumberFormat('dd.mm.yyyy');
sheet.getRangeByIndexes(2,2,rows.length,2).setNumberFormat('#,##0');
sheet.freezePanes.freezeRows(2);
sheet.tables.add(`A2:M${rows.length+2}`,true,'LocksmithCategoryKeywords').style='TableStyleMedium2';
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:`Слесари!A1:M${rows.length+2}`,include:'values,formulas',tableMaxRows:10,tableMaxCols:13})).ndjson);
const png=await wb.render({sheetName:'Слесари',range:`A1:F${rows.length+2}`,scale:1.5,format:'png'});
await fs.writeFile(`${qa}/slesari-preview.png`,new Uint8Array(await png.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(`${qa}/candidate-Семантическое ядро Сайт АБС.xlsx`);
